// The optional copies from Pocock that ticket #75 adds: what the kit promises
// about each one in its manifests, its notice and its docs. The sync `check`
// and validate-kit hold the rules for every copy; these tests hold what is
// particular to these ones, such as which upstream invocation mode each keeps.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { repoRoot } from './fixtures.mjs';

const read = (path) => readFileSync(join(repoRoot, path), 'utf8');

// The pin as ticket #75 states it. Moving it is a decision of its own.
const PIN = 'd1478fcb140db0b93c0c8df17bcfd311844749d0';

const COPIES = [
  { name: 'wizard', folder: 'skills/engineering/wizard', userInvoked: false },
  { name: 'to-questionnaire', folder: 'skills/productivity/to-questionnaire', userInvoked: true },
  { name: 'wait-what', folder: 'skills/productivity/wait-what', userInvoked: true },
];

for (const { name, folder, userInvoked } of COPIES) {
  const skill = `aw-${name}`;

  test(`${skill} is listed in upstreams.json at the pin, from its upstream folder`, () => {
    const { mattpocock } = JSON.parse(read('upstreams.json')).upstreams;
    assert.equal(mattpocock.commit, PIN);
    assert.equal(mattpocock.skills[name], folder);
  });

  test(`${skill} carries the upstream license and its renamed name`, () => {
    assert.ok(existsSync(join(repoRoot, 'skills', skill, 'LICENSE.upstream')));
    assert.match(read(`skills/${skill}/SKILL.md`), new RegExp(`^name: ${skill}$`, 'm'));
  });

  test(`${skill} stays ${userInvoked ? 'user-invoked' : 'model-invoked'}, as upstream has it`, () => {
    const frontmatterFlag = /^disable-model-invocation: true$/m.test(read(`skills/${skill}/SKILL.md`));
    const yamlFlag = /allow_implicit_invocation: false/.test(read(`skills/${skill}/agents/openai.yaml`));
    assert.equal(frontmatterFlag, userInvoked);
    assert.equal(yamlFlag, userInvoked);
  });

  test(`${skill} has a NOTICE.md row of kind copy and a line in plugin.json`, () => {
    const row = read('NOTICE.md').split('\n').find((line) => line.startsWith(`| \`${skill}\` |`));
    assert.ok(row, 'no NOTICE.md row');
    assert.match(row, new RegExp(`\`${folder}\``));
    assert.match(row, /\[`d1478fc`\]/);
    assert.match(row, /\| copy \|$/);
    const { skills } = JSON.parse(read('.claude-plugin/plugin.json'));
    assert.ok(skills.includes(`./skills/${skill}`), 'no plugin.json line');
  });
}

test('aw-wizard keeps its Bash template, with its slash command renamed', () => {
  assert.match(read('skills/aw-wizard/template.sh'), /^# Generated by the \/aw-wizard skill\.$/m);
});

test('the README status line counts fourteen copies from Pocock and one from Addy Osmani, as upstreams.json lists', () => {
  const { mattpocock, addyosmani } = JSON.parse(read('upstreams.json')).upstreams;
  assert.equal(Object.keys(mattpocock.skills).length, 14);
  assert.equal(Object.keys(addyosmani.skills).length, 1);
  assert.match(read('README.md'), /It ships fourteen copies of Matt Pocock's skills and one of Addy Osmani's so far/);
});

test("ADR 0010's list of phase-free copies names every copy in upstreams.json", () => {
  const adr = read('docs/adr/0010-one-owner-per-phase-and-slices-in-the-spec.md');
  const list = adr.split('\n').find((line) => line.startsWith('Phase-free copies sit outside the table:'));
  assert.ok(list, 'no list of phase-free copies');
  const { upstreams } = JSON.parse(read('upstreams.json'));
  for (const { skills } of Object.values(upstreams)) {
    for (const name of Object.keys(skills)) assert.ok(list.includes(`\`aw-${name}\``), `the list leaves out aw-${name}`);
  }
});

test('no kit skill names these copies, so no phase, route or gate depends on them', () => {
  const { upstreams } = JSON.parse(read('upstreams.json'));
  const copies = new Set(Object.values(upstreams).flatMap(({ skills }) => Object.keys(skills).map((name) => `aw-${name}`)));
  const kitSkills = readdirSync(join(repoRoot, 'skills')).filter((folder) => !copies.has(folder));
  assert.ok(kitSkills.includes('aw-ship'), 'the kit skills were not found');
  for (const folder of kitSkills) {
    for (const entry of readdirSync(join(repoRoot, 'skills', folder), { recursive: true })) {
      if (!entry.endsWith('.md')) continue;
      const text = read(join('skills', folder, entry));
      for (const { name } of COPIES) assert.ok(!text.includes(`aw-${name}`), `${folder}/${entry} names aw-${name}`);
    }
  }
});
